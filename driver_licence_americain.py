import json
from datetime import date, datetime
import hashlib

# --- Fonctions de calcul ---

def calc_expiration(dob: date, issue_date: date):
    """Calcule la date d'expiration pour < 70 ans (5 ans après l'émission, sur l'anniversaire)."""
    exp_year = issue_date.year + 5
    return date(exp_year, dob.month, dob.day)

def calc_dl(last_name: str, dob: date):
    """Simule un numéro de permis (DL) : initiale du nom + 7 chiffres dérivés de la date de naissance."""
    letter = last_name[0].upper()
    dob_str = dob.strftime("%Y%m%d")
    h = hashlib.sha1(dob_str.encode()).hexdigest()
    digits = ''.join([c for c in h if c.isdigit()])[:7]
    return letter + digits

def calc_dd(issue_date: date):
    """Simule un Document Discriminator (DD) basé sur la date d'émission + code interne."""
    code = issue_date.strftime("%m%d%Y")
    suffix = hashlib.md5(code.encode()).hexdigest()[:6]
    return f"{code}{suffix}"

