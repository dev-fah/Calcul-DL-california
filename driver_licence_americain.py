st.title("CALCUL DES INFO SUR UN DL CALIFORNIA")

# Formulaire utilisateur
ln = st.text_input("Nom de famille (LN)", "Harms")
fn = st.text_input("Prénom (FN)", "Rosa")
dob_str = st.text_input("Date de naissance (DOB, format YYYY-MM-DD)", "1990-12-31")
iss_str = st.text_input("Date d'émission (ISS, format YYYY-MM-DD)", "2015-09-30")

if st.button("Calculer"):
    dob = datetime.strptime(dob_str, "%Y-%m-%d").date()
    iss = datetime.strptime(iss_str, "%Y-%m-%d").date()

    dl = calc_dl(ln, dob)
    exp = calc_expiration(dob, iss)
    dd = calc_dd(iss)

    # Résultats
    st.subheader("Résultats simulés")
    st.write(f"DL : {dl}")
    st.write(f"EXP : {exp}")
    st.write(f"ISS : {iss}")
    st.write(f"DD : {dd}")
    st.write(f"LN : {ln}")
    st.write(f"FN : {fn}")
    st.write(f"DOB : {dob}")
